"""Fetch all sources, build threat_data, and describe what changed.

Failure policy: VCDB and ATT&CK are required (they produce the prevalence and the
control links). KEV and EUVD only adjust the exploitation trend; if one is down
the update continues without it and the change report says so. If a required
source fails, the previous values are kept and the update reports an error.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path

import yaml

from ..controls import Catalogue
from ..weighting import compute_weights
from . import compute, sources
from .data import ThreatData
from .patterns import load_patterns

WEIGHT_FLAG = 0.25       # flag control weight changes of at least this much
PREVALENCE_FLAG = 0.05   # flag pattern prevalence changes of at least 5 percentage points


def collect(
    today: dt.date,
    source_dir: Path | None = None,
    window_years: int = 5,
    min_sample: int = 300,
) -> tuple[dict, list[str]]:
    """Return (threat_data, warnings)."""
    patterns = load_patterns()
    warnings: list[str] = []
    meta: dict[str, dict] = {}

    records, meta["vcdb"] = sources.get_vcdb(source_dir)
    vcdb = compute.vcdb_prevalence(records, patterns, today, window_years, min_sample)
    meta["vcdb"]["records"] = len(records)
    if vcdb["below_min_sample"]:
        warnings.append(
            f"VCDB sample is only {vcdb['sample_size']} incidents, below the minimum of {min_sample}."
        )

    bundle, meta["mitre_attack"] = sources.get_attack(source_dir)
    attack = compute.attack_links(bundle, patterns)

    kev = euvd = None
    try:
        kev_raw, meta["cisa_kev"] = sources.get_kev(source_dir)
        kev = compute.kev_indicator(kev_raw, today)
    except sources.SourceError as exc:
        warnings.append(f"CISA KEV unavailable, trend computed without it: {exc}")
        meta["cisa_kev"] = {"status": "unavailable"}

    try:
        current, previous = compute.windows(today)
        counts, meta["enisa_euvd"] = sources.get_euvd_counts(current, previous, source_dir)
        euvd = compute.euvd_indicator(counts)
    except sources.SourceError as exc:
        warnings.append(f"ENISA EUVD unavailable, trend computed without it: {exc}")
        meta["enisa_euvd"] = {"status": "unavailable"}

    for m in meta.values():
        m.setdefault("status", "ok")

    data = compute.build_threat_data(patterns, vcdb, attack, kev, euvd, meta, today)
    return data, warnings


def write_threat_data(data: dict, path: str | Path) -> None:
    header = (
        "# Generated by `nis2check update-threat-data`. Do not edit by hand:\n"
        "# change nis2check/data/patterns.yaml or the catalogue, then re-run the update.\n"
    )
    Path(path).write_text(
        header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100), "utf-8"
    )


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def change_report(
    catalogue: Catalogue, old: ThreatData | None, new: ThreatData, warnings: list[str]
) -> tuple[str, bool]:
    """Markdown summary of the update for a pull request. Returns (markdown, has_changes)."""
    lines = [f"## Threat data update, {new.generated}", ""]
    v = new.vcdb
    lines += [
        f"- VCDB window {v['window']['from_year']}-{v['window']['to_year']}, "
        f"{v['sample_size']} incidents",
        f"- MITRE ATT&CK v{new.sources.get('mitre_attack', {}).get('version', '?')}",
        f"- Exploitation trend factor {new.trend.get('factor')}"
        f" (CISA KEV: {_ratio(new.trend.get('cisa_kev'))}, ENISA EUVD: {_ratio(new.trend.get('enisa_euvd'))})",
        "",
    ]
    if warnings:
        lines += ["### Warnings", ""] + [f"- {w}" for w in warnings] + [""]

    changed = False
    lines += ["### Threat patterns", "", "| Pattern | Before | After | Change | |", "|---|---|---|---|---|"]
    for pid, info in new.patterns.items():
        before = old.patterns.get(pid, {}).get("adjusted_prevalence") if old else None
        after = info["adjusted_prevalence"]
        delta = None if before is None else after - before
        flag = "FLAG" if delta is not None and abs(delta) >= PREVALENCE_FLAG else ""
        if delta is None or abs(delta) > 1e-9:
            changed = True
        lines.append(
            f"| {info['name']} | {_pct(before)} | {_pct(after)} | "
            f"{'new' if delta is None else f'{delta * 100:+.1f} pp'} | {flag} |"
        )

    mapping_changes = []
    for pid, info in new.patterns.items():
        before = set(old.patterns.get(pid, {}).get("attack_mitigations", [])) if old else set()
        after = set(info.get("attack_mitigations", []))
        if old and before != after:
            added, removed = sorted(after - before), sorted(before - after)
            mapping_changes.append(
                f"- {info['name']}: added {', '.join(added) or 'none'}; removed {', '.join(removed) or 'none'}"
            )
    if mapping_changes:
        changed = True
        lines += ["", "### ATT&CK mitigation links", ""] + mapping_changes

    new_w = compute_weights(catalogue, new, "threat")
    old_w = compute_weights(catalogue, old, "threat") if old else {}
    rows = []
    for qid, w in new_w.items():
        before = old_w.get(qid).weight if qid in old_w else None
        if before is None or abs(w.weight - before) >= 0.01:
            delta = None if before is None else w.weight - before
            flag = "FLAG" if delta is not None and abs(delta) >= WEIGHT_FLAG else ""
            rows.append((abs(delta or 0), f"| {qid} | {before if before is not None else 'n/a'} | "
                         f"{w.weight} | {'new' if delta is None else f'{delta:+.2f}'} | {flag} |"))
    lines += ["", "### Control weights", ""]
    if rows:
        changed = True
        lines += ["| Control | Before | After | Change | |", "|---|---|---|---|---|"]
        lines += [r for _, r in sorted(rows, reverse=True)]
    else:
        lines.append("No control weights changed.")

    lines += [
        "",
        "---",
        f"Review flagged rows (pattern change of {PREVALENCE_FLAG * 100:.0f} pp or more, weight change "
        f"of {WEIGHT_FLAG} or more) before merging. Merging this pull request changes the "
        "weights used in every new report.",
    ]
    return "\n".join(lines) + "\n", changed


def _ratio(ind: dict | None) -> str:
    if not ind:
        return "unavailable"
    if ind.get("ratio") is None:
        return f"{ind.get('current')} in last 12 months"
    return f"{ind['current']} vs {ind['previous']} newly exploited, x{ind['ratio']}"
